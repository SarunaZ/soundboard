from playwright.sync_api import sync_playwright
from pathlib import Path
import json
base=Path(__file__).resolve().parents[1]
out=base/'previews'
results={}
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 page=browser.new_page(viewport={'width':1260,'height':980}, device_scale_factor=1)
 page.set_default_timeout(3500)
 errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.set_content((base/'prototype'/'standalone.html').read_text(), wait_until='load')
 def chk(k,expected=True):
  print('CHECK',k,expected,flush=True)
  results[k]=expected
  if not expected: print('FAIL',k)
 # baseline normal
 chk('pad_more_hidden_normal',page.locator('.pad-menu-trigger').count()==0)
 chk('quick_first_normal',page.locator('.grid-wrap>.sound-pad').first.evaluate("e=>e.classList.contains('quick')"))
 chk('quick_arrow_hidden_normal',page.locator('.quick-arrow').count()==0)
 chk('default_4x4',page.locator('.grid-wrap').get_attribute('data-grid')=='4x4')
 chk('default_page_16',page.locator('.grid-wrap>.sound-pad').count()==16)
 page.locator('[data-action="settingsMenu"]').click();page.locator('[data-action="openSettings"]').click()
 chk('only_master_and_background_in_playback',page.locator('section.settings-section').first.locator('input').count()==2)
 chk('pad_progress_toggle_absent',page.get_by_text('Show pad progress').count()==0)
 chk('tap_mode_absent',page.get_by_text('Tap an active pad').count()==0)
 chk('global_overlap_absent',page.get_by_text('Allow overlapping sounds').count()==0)
 chk('default_repeat_absent',page.get_by_text('Default replay mode').count()==0)
 chk('board_options_absent_from_settings',page.get_by_text('Board behavior').count()==0)
 page.screenshot(path=str(out/'simplified-settings-vanilla.png'))
 page.locator('#theme-select').select_option('Coffee')
 page.screenshot(path=str(out/'simplified-settings-coffee.png'))
 page.locator('[data-action="closeSettings"]').click()
 page.screenshot(path=str(out/'simplified-board-normal-coffee.png'))
 page.locator('[data-action="editBoard"]').click()
 chk('edit_mode_pad_menus_visible',page.locator('.pad-menu-trigger').count()==15)
 chk('edit_mode_quick_arrow_visible',page.locator('.quick-arrow').count()==1)
 chk('board_grid_editor_visible',page.locator('.grid-size-control[aria-label="Board grid size"]').count()==1)
 page.screenshot(path=str(out/'edit-board-4x4-coffee.png'))
 page.locator('[data-action="setGrid"][data-value="3x4"]').click()
 chk('layout_switch_3x4',page.locator('.grid-wrap').get_attribute('data-grid')=='3x4')
 chk('3x4_total_12_tiles',page.locator('.grid-wrap>.sound-pad').count()==12)
 chk('page_count_2',page.get_by_text('Page 1 of 2').count()==1)
 page.screenshot(path=str(out/'edit-board-3x4-coffee.png'))
 page.locator('[data-action="boardPage"][data-value="1"]').click()
 chk('page_two_visible',page.get_by_text('Page 2 of 2').count()==1)
 chk('quick_first_page2',page.locator('.grid-wrap>.sound-pad').first.evaluate("e=>e.classList.contains('quick')"))
 page.screenshot(path=str(out/'edit-board-3x4-page2-coffee.png'))
 page.locator('[data-action="boardPage"][data-value="0"]').click()
 page.locator('[data-action="padMenu"]').first.click()
 chk('pad_menu_open_edit_mode',page.locator('[data-action="clipSettings"]').count()==1)
 page.locator('[data-action="clipSettings"]').click()
 chk('per_sound_max_200',page.locator('#clip-gain').get_attribute('max')=='200')
 page.locator('#clip-gain').fill('165')
 chk('gain_pct_label',page.locator('#clip-volume-readout').inner_text()=='165%')
 chk('gain_db_label',page.locator('#gain-db-readout').inner_text()=='4.3 dB')
 chk('repeat_once_default',page.locator('#setting-clipRepeat').input_value()=='once')
 page.locator('#setting-clipRepeat').select_option('loop')
 page.screenshot(path=str(out/'clip-volume-boost-coffee.png'))
 page.locator('[data-action="saveClipSettings"]').click()
 chk('sound_gain_persist_ui',page.evaluate("state.sounds.find(s=>s.id==='red-sun').gain") ==165)
 chk('sound_repeat_persist_ui',page.evaluate("state.sounds.find(s=>s.id==='red-sun').repeat") =='loop')
 page.locator('[data-action="editBoard"]').click()
 chk('menu_hidden_after_edit',page.locator('.pad-menu-trigger').count()==0)
 chk('quick_arrow_hidden_after_edit',page.locator('.quick-arrow').count()==0)
 page.locator('[data-action="playSound"]').first.click()
 page.wait_for_timeout(300)
 chk('pad_progress_always',page.locator('.pad-progress.is-visible').count()==1)
 chk('stop_all_contextual',page.locator('[data-action="stopAll"]').count()==1)
 page.locator('[data-action="playSound"]').nth(1).click()
 chk('single_by_default',page.evaluate('Object.keys(state.soundSessions).length')==1)
 page.locator('[data-action="stopAll"]').click()
 # overlap board specific
 page.locator('[data-action="editBoard"]').click()
 page.locator('[data-setting="boardOverlap"]').check()
 chk('board_overlap_on',page.evaluate('state.boardPlayback[state.board]') is True)
 page.locator('[data-action="editBoard"]').click()
 page.locator('[data-action="playSound"]').first.click();page.locator('[data-action="playSound"]').nth(1).click()
 chk('board_overlap_two_sessions',page.evaluate('Object.keys(state.soundSessions).length')==2)
 # Board-specific grid prefs
 page.locator('[data-action="stopAll"]').click()
 page.locator('[data-action="boardMenu"]').click();page.locator('[data-action="selectBoard"][data-value="Work"]').click()
 chk('second_board_default_4x4',page.locator('.grid-wrap').get_attribute('data-grid')=='4x4')
 page.locator('[data-action="boardMenu"]').click();page.locator('[data-action="selectBoard"][data-value="Main board"]').click()
 chk('main_board_grid_persist',page.locator('.grid-wrap').get_attribute('data-grid')=='3x4')
 # All themes settings + edit grids
 for theme in ['Peach','Mint','Snow','Ice','Vanilla','Coffee']:
  page.locator('#theme-select').select_option(theme)
  page.locator('[data-action="editBoard"]').click()
  chk('edit_theme_'+theme,page.locator('.grid-size-control[aria-label="Board grid size"]').is_visible())
  page.locator('[data-action="editBoard"]').click()
 # keyboard font size 360 width
 page.set_viewport_size({'width':375,'height':820})
 page.evaluate("state.theme='Vanilla';render(false)")
 page.locator('[data-action="editBoard"]').click()
 page.screenshot(path=str(out/'edit-board-3x4-mobile-vanilla.png'))
 chk('mobile_grid_visible',page.locator('.grid-size-control[aria-label="Board grid size"]').is_visible())
 chk('js_errors_none',not errors)
 results['errors']=errors
 (base/'design'/'simplified-validation.json').write_text(json.dumps(results,indent=2))
 print(json.dumps(results,indent=2))
 browser.close()
assert all(v for k,v in results.items() if k!='errors')
